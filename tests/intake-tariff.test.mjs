test('all columns and later decrees remain discoverable, literal mentions do not become tax rows',()=>{
 const {results}=searchTariff('04014002',0);
 assert.deepEqual(results.map(r=>r.page),[40,856,862,891]);
 assert.equal(results.find(r=>r.page===862).row,null);
 assert.match(tariffResult('0401.40.02',40).row.description,/2025/);
 assert.deepEqual(searchTariff('00000000',0),{results:[],total:0});
 for(const term of ['1234567890','8413.7','',{},'0301/0500'])assert.throws(()=>searchTariff(term,0));
 assert.throws(()=>tariffResult('0401.40.02',861));
 const codes=labeledTariffCodes('RFC: 84137007\nFolio: 8413.70.07\nFracción propuesta: 8413700700\nFracción arancelaria propuesta: 84137007.\nFracción: 8413.70.07');
 assert.deepEqual(codes,[{code:'8413.70.07',line:4,excerpt:'Fracción arancelaria propuesta: 84137007.'}]);
});
test('two engines agree on checked cells, merged pages carry both locators and description searches are paginated',()=>{
 const row=tariffResult('8414.30.05',631);
 assert.deepEqual(row.row.continued,[632]);assert.match(row.row.description,/desplazamiento volumétrico de hasta 15 m³ por minuto/);
 assert.match(tariffReference(row.code,row.page).locator,/pp. 631 y 632/);
 assert.ok(searchTariff('desplazamiento volumetrico',0).results.some(r=>r.code===row.code));
 const first=searchTariff('bomba',0),next=searchTariff('bomba',12);assert.ok(first.total>12&&next.results.length);
 assert.ok(!first.results.some(a=>next.results.some(b=>a.code===b.code&&a.page===b.page)));
 assert.ok(!tariffResult('8413.70.99',631).canFollow);assert.throws(()=>tariffResearch('0401.40.02',862));
 const atom=tariffResearch('8413.70.07',631);assert.match(atom.ref.text,/limpiaparabrisas/);assert.throws(()=>researchEnvelope(atom));
});
test('a local tariff file remains editable and exportable without a provider and rejects forged page content',async t=>{
 const dataDir=await mkdtemp(path.join(tmpdir(),'rejon-tarifa-'));
 let calls=0;
 const app=await startServer({intakePilot:true,intakeGenerate:async()=>{calls++;throw Error();},dataDir,autoInitialize:false,pilotPassphrase:Buffer.from('frase temporal para ensayo')});
 t.after(async()=>{await app.close();await rm(dataDir,{recursive:true,force:true});});
 const rpc=(action,payload)=>app.service.dispatch('intake.'+action,payload);
 await rpc('save',{firm:'Despacho ficticio',client:'Empresa de Prueba',title:'Operación azul',jurisdiction:'MX-FED'});
 await assert.rejects(rpc('addTariff',{code:'8413.70.07',page:631,description:'dato del cliente'}));
 const first=await rpc('addTariff',{code:'04014002',page:862});
 assert.ok(!first.status.followupParents.includes(first.task));
 const saved=await rpc('addTariff',{code:'8413.70.07',page:631});
 assert.ok(saved.status.followupParents.includes(saved.task));
 const amended=saved.status.drafts[saved.task]+'\nObservación privada agregada.';
 await rpc('edit',{task:saved.task,text:amended});
 assert.equal((await rpc('addTariff',{code:'84137007',page:631})).status.drafts[saved.task],amended);
 const file=await rpc('export',{task:saved.task,format:'docx'});assert.match(file.name,/\.docx$/);
 const planned=await rpc('addFollowup',{task:saved.task,form:'carta',instruction:'Pide la ficha técnica de la Empresa de Prueba.'});
 const note=planned.status.tasks.find(item=>item.id===planned.task);
 assert.match(note.preview,/sistema de limpiaparabrisas/);
 assert.ok(!note.preview.includes('Observación privada')&&!note.preview.includes('Empresa de Prueba'));
 const {default:ExcelJS}=await import('exceljs');
 const book=new ExcelJS.Workbook();
 const comparison=await rpc('exportTariffBook',{});
 await book.xlsx.load(Buffer.from(comparison.base64,'base64'));
 const table=book.getWorksheet('Tarifa consultada');
 assert.deepEqual([table.getCell('A2').value,table.getCell('A3').value],['0401.40.02','8413.70.07']);
 assert.equal(table.getCell('B2').value,862);assert.equal(table.getCell('F2').value,'');
 assert.equal(table.getCell('F3').value,'Ex.');assert.equal(table.getCell('I3').value.hyperlink,saved.status.tasks.find(item=>item.id===saved.task).references[0].url);
 assert.equal(calls,0);
});
